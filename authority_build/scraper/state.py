"""Phase state persistence + authority_index.py writer."""
import json
from pathlib import Path

HERE = Path(__file__).parent.parent           # authority_build/
PARENT = HERE.parent                          # vakeel_beta/

OUTPUT_INDEX = PARENT / "authority_index.py"

STATE_PATHS = {
    "phase0": HERE / "ik_scrape_state.json",          # resolved from phase 0 (already exists)
    "phase1": HERE / "phase1_citedby_state.json",
    "phase2": HERE / "phase2_parallels_state.json",
}


def load_state(phase: str, fresh: bool = False) -> dict:
    p = STATE_PATHS[phase]
    if fresh and p.exists():
        p.unlink()
    if p.exists():
        return json.loads(p.read_text(encoding="utf-8"))
    if phase == "phase0":
        return {"resolved": {}, "failed": []}
    if phase == "phase1":
        return {"processed_seed_tids": [], "new_resolved": {}, "failed": []}
    if phase == "phase2":
        return {"processed_tids": [], "citations_by_tid": {}}
    return {}


def save_state(phase: str, state: dict):
    p = STATE_PATHS[phase]
    tmp = p.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(state, indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(p)


RESOLVER_CODE = '''
import re

def _normalize(s: str) -> str:
    s = (s or "").lower().replace(".", " ")
    return re.sub(r"\\s+", " ", s).strip()


def resolve_case_name(variant: str):
    LEGAL_STARTERS = {
        "Section", "Article", "Under", "Whether", "When", "What",
        "How", "Where", "Which", "Can", "Is", "Are", "Does", "Order",
    }
    parts = variant.split()
    name_tokens = []
    for tok in parts:
        clean = tok.rstrip(".,")
        if clean in LEGAL_STARTERS or (clean and clean[0].isdigit()):
            break
        if clean and clean[0].isupper() and len(clean) >= 2:
            name_tokens.append(tok)
        else:
            break
    if not name_tokens:
        return None
    name = _normalize(" ".join(name_tokens))
    if name in AUTHORITY_INDEX:
        return AUTHORITY_INDEX[name]
    tokens = name.split()
    for i in range(len(tokens) - 1, 0, -1):
        prefix = " ".join(tokens[:i])
        if prefix in AUTHORITY_INDEX:
            return AUTHORITY_INDEX[prefix]
    return None
'''


def write_authority_index(alias_map: dict, by_tid_info: dict):
    """
    alias_map: {alias_str: {"tid": "...", "info": {...}} or None for ambiguous}
    by_tid_info: {tid: {"title": "...", "reason": "...", ...}}
    Writes vakeel_beta/authority_index.py.
    """
    # Drop ambiguous (None) entries
    valid = {a: v for a, v in alias_map.items() if v is not None}

    high, medium = [], []
    for alias, v in sorted(valid.items()):
        tid = v["tid"]
        info = by_tid_info.get(tid, {})
        reason = info.get("reason", "")
        title = info.get("title", "")
        bucket = high if reason == "citation-verified" else medium
        bucket.append((alias, tid, title))

    ambiguous_count = sum(1 for v in alias_map.values() if v is None)

    lines = [
        '"""',
        'Auto-generated by authority_build/scrape_ik.py',
        'Cases verified by IK public-website citation search + body match.',
        '',
        f'Total aliases: {len(valid)}',
        f'  HIGH:   {len(high)} (citation found in document body)',
        f'  MEDIUM: {len(medium)} (top SC result for citation phrase)',
        f'  AMBIGUOUS: {ambiguous_count} aliases dropped (mapped to multiple cases)',
        '"""',
        "",
        "AUTHORITY_INDEX: dict[str, str] = {",
    ]
    if high:
        lines.append("    # ── HIGH (citation-verified) ──")
        for a, t, ti in high:
            lines.append(f'    "{a}": "{t}",  # {ti[:70]}')
    if medium:
        lines.append("    # ── MEDIUM (top SC result, unverified body) ──")
        for a, t, ti in medium:
            lines.append(f'    "{a}": "{t}",  # {ti[:70]}')
    lines.append("}")
    lines.append(RESOLVER_CODE)
    OUTPUT_INDEX.write_text("\n".join(lines), encoding="utf-8")
    return len(valid), len(high), len(medium), ambiguous_count
